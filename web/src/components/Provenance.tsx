import type { Inspection } from "../api";
import { formatMs, formatTimestamp, PAIR_SKEW_WARNING_MS } from "../book";
import { formatAge, formatCount, isStale } from "../format";
import styles from "./Provenance.module.css";

export interface ProvenanceProps {
  inspection: Inspection;
  /** When the browser received the answer (local clock). */
  receivedAt: number;
  now: number;
}

/** When and how the shown books were observed, and what the inspection cost. */
export function Provenance({ inspection: x, receivedAt, now }: ProvenanceProps) {
  const stale = isStale(receivedAt, now);
  const skewWarn = x.pairSkewMs > PAIR_SKEW_WARNING_MS;
  return (
    <section className={styles.provenance} aria-label="Freshness and provenance">
      <h3 className={styles.title}>Freshness and provenance</h3>
      <p className={stale ? styles.stale : styles.fresh} role={stale ? "status" : undefined}>
        {stale ? `Stale: inspected ${formatAge(now - receivedAt)}. Refresh to observe the books again.` : `Inspected ${formatAge(now - receivedAt)}.`}
      </p>
      <dl className={styles.facts}>
        <dt>Answer generated by the local server</dt>
        <dd className="mono">{formatTimestamp(x.generatedAt)}</dd>
        {x.outcomes.map((o) => (
          <BookTimes key={o.index} outcome={o} />
        ))}
        <dt>Gap between the two book responses</dt>
        <dd className={skewWarn ? styles.warn : "mono"}>
          {formatMs(x.pairSkewMs)}
          {skewWarn ? ` (more than ${formatMs(PAIR_SKEW_WARNING_MS)})` : ""}
        </dd>
        <dt>Requests to Polymarket for this inspection</dt>
        <dd>
          {formatCount(x.budget.call.used)} of at most {formatCount(x.budget.call.limit)}
        </dd>
        <dt>Server requests left</dt>
        <dd>
          {formatCount(x.budget.process.remaining)} of {formatCount(x.budget.process.limit)}
        </dd>
      </dl>
      <p className={styles.note}>
        The books are separate requests made one after another, not an atomic snapshot: one may have changed before the other was read. Polymarket&apos;s own book timestamp is
        shown as reported; an old timestamp alone does not prove a book is stale.
      </p>
      <details className={styles.details}>
        <summary>Requests made ({x.requests.length})</summary>
        <table className={styles.requests}>
          <thead>
            <tr>
              <th scope="col">Source</th>
              <th scope="col">Endpoint</th>
              <th scope="col">HTTP</th>
              <th scope="col">Attempts</th>
              <th scope="col">Time</th>
            </tr>
          </thead>
          <tbody>
            {x.requests.map((r, i) => (
              <tr key={i}>
                <td>{r.source === "gamma" ? "Gamma" : "CLOB"}</td>
                <td className="mono">{r.endpoint}</td>
                <td>{r.httpStatus ?? "None"}</td>
                <td>{r.attempts}</td>
                <td>{r.durationMs === null ? "Unknown" : formatMs(r.durationMs)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </details>
    </section>
  );
}

function BookTimes({ outcome: o }: { outcome: Inspection["outcomes"][number] }) {
  return (
    <>
      <dt>
        <span className={styles.outcome}>{o.label}</span> book: Polymarket timestamp
      </dt>
      <dd className="mono">{formatTimestamp(o.book.serverTimestamp.iso)}</dd>
      <dt>
        <span className={styles.outcome}>{o.label}</span> book: received by the local server
      </dt>
      <dd className="mono">{formatTimestamp(o.request.responseReceivedAt)}</dd>
    </>
  );
}
